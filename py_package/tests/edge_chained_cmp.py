# Edge: 比较链 a < b < c

print(1 < 2 < 3)           # True
print(1 < 2 > 3)           # False
print(3 > 2 > 1)           # True
print(1 < 2 == 2)          # True
print(1 == 2 < 3)          # False
print(5 > 3 < 4)           # True
print(5 > 3 > 1)           # True
print(1 < 2 < 3 < 4)       # True
print(1 <= 1 < 2)          # True
print(1 < 2 >= 2)          # True