print(7 // -2, 7 % -2)
print(-1 // 3, -1 % 3)
print(1 // -3, 1 % -3)
print(-5 // 2, -5 % 2)
print(-7.0 % 2, 7 % -2.0)
print(-7.0 // 2)
print(divmod(-7, 2), divmod(7, -2))
print(divmod(-7.0, 2), divmod(7.0, -2))
