# 列表/元组/集合字面量 * 解包测试 (Python 3.5+)

a = [1, 2, 3]
b = [4, 5]

# 列表字面量解包
print([*a, 6])              # [1, 2, 3, 6]
print([0, *a])              # [0, 1, 2, 3]
print([*a, *b])             # [1, 2, 3, 4, 5]
print([*a, 9, *b])          # [1, 2, 3, 9, 4, 5]
print([*a])                 # [1, 2, 3]
print([*[], 1])             # [1]
print([1, *[]])             # [1]

# 解包任意可迭代对象
print([*"ab", "c"])         # ['a', 'b', 'c']
print([*range(3)])          # [0, 1, 2]
print([*{"x": 1}])          # ['x'] (字典迭代键)
print(sorted([*{3, 1, 2}])) # [1, 2, 3]

# 元组字面量解包
print((*a,))                # (1, 2, 3)
print((*a, 6))              # (1, 2, 3, 6)
print((0, *a, *b))          # (0, 1, 2, 3, 4, 5)
print((*"ab",))             # ('a', 'b')

# 集合字面量解包
print(sorted({*a}))         # [1, 2, 3]
print(sorted({*a, 10}))     # [1, 2, 3, 10]
print(sorted({*a, *b}))     # [1, 2, 3, 4, 5]

# 嵌套解包
print([*[*a, 4], 5])        # [1, 2, 3, 4, 5]

# 解包不改变原对象
print(a)                    # [1, 2, 3]
print(b)                    # [4, 5]

# 解包结果可继续参与表达式
print(len([*a, *b]))        # 5
print([*a, *b][1:4])        # [2, 3, 4]

print("done")
