# Edge: ord / chr / hex / oct / bin

print(ord("A"))              # 65
print(ord("a"))              # 97
print(ord("0"))              # 48
print(chr(65))               # A
print(chr(97))               # a
print(chr(48))               # 0

print(hex(255))              # 0xff
print(hex(16))               # 0x10
print(oct(8))                # 0o10
print(oct(64))               # 0o100
print(bin(5))                # 0b101
print(bin(255))              # 0b11111111

print("done")