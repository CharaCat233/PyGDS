# Edge: 位运算

print(1 & 1)               # 1
print(1 & 0)               # 0
print(0 & 1)               # 0
print(3 & 5)               # 1
print(1 | 1)               # 1
print(1 | 0)               # 1
print(0 | 1)               # 1
print(3 | 5)               # 7
print(1 ^ 1)               # 0
print(1 ^ 0)               # 1
print(0 ^ 1)               # 1
print(3 ^ 5)               # 6
print(~0)                  # -1
print(~1)                  # -2
print(~(-1))               # 0
print(1 << 1)              # 2
print(1 << 3)              # 8
print(8 >> 1)              # 4
print(8 >> 3)              # 1
print(-8 >> 1)             # -4